/**
 * Build the immutable toolchain assets a consumer installs without npm.
 *
 * - core, style-contract and style-test-kit are packed as tarballs;
 * - the lint package contributes its self-contained ESM bundle;
 * - every file lands under `artifacts/`, which is git-ignored and rebuilt from
 *   a checked-out revision.
 *
 * The manifest generator hashes these files afterwards, so a consumer lock can
 * name one toolchain revision and verify the bytes it received.
 */
import { execFileSync } from "node:child_process";
import { cp, mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { ARTIFACT_PACKAGES, artifactFileName } from "./artifact-names.mjs";

const rootDir = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const artifactsDir = path.join(rootDir, "artifacts");
const pnpm = process.platform === "win32" ? "pnpm.cmd" : "pnpm";

const packageDirectories = {
  "@banyan/core": "core",
  "@banyan/style-contract": "style-contract",
  "eslint-plugin-banyan-style": "eslint-plugin",
  "@banyan/style-test-kit": "style-test-kit",
};
const packageVersions = {};
for (const [name, directory] of Object.entries(packageDirectories)) {
  const packageJSON = JSON.parse(
    await readFile(
      path.join(rootDir, "packages", directory, "package.json"),
      "utf8",
    ),
  );
  packageVersions[name] = packageJSON.version;
}
const exampleArtifact = (name) => artifactFileName(name, packageVersions[name]);

for (const [key, name] of Object.entries(ARTIFACT_PACKAGES)) {
  if (!packageVersions[name]) {
    throw new Error(`Missing package version for ${name} (${key})`);
  }
}

async function pack(filter) {
  execFileSync(
    pnpm,
    ["--filter", filter, "pack", "--pack-destination", artifactsDir],
    { cwd: rootDir, stdio: "inherit", shell: process.platform === "win32" },
  );
}

await rm(artifactsDir, { recursive: true, force: true });
await mkdir(artifactsDir, { recursive: true });

await pack("@banyan/style-contract");
await pack("@banyan/core");
await pack("eslint-plugin-banyan-style");
await pack("@banyan/style-test-kit");

const lintDist = path.join(rootDir, "packages", "eslint-plugin", "dist");
await cp(
  path.join(lintDist, "eslint-plugin-banyan-style.mjs"),
  path.join(artifactsDir, "eslint-plugin-banyan-style.mjs"),
);
await cp(
  path.join(lintDist, "build-metadata.json"),
  path.join(artifactsDir, "eslint-plugin-banyan-style.build.json"),
);

const artifactNames = await readdir(artifactsDir);

await writeFile(
  path.join(artifactsDir, "README.md"),
  `# Toolchain artifacts

Generated by \`pnpm pack:artifacts\` from one toolchain revision. Do not edit.

Install order for a consumer without npm:

1. \`banyan-style-contract-*.tgz\`
2. \`banyan-core-*.tgz\`
3. \`eslint-plugin-banyan-style-*.tgz\`
4. \`banyan-style-test-kit-*.tgz\` (test-only)

The packages use ordinary semver dependencies on each other (pnpm rewrites
\`workspace:*\` when packing), so a consumer outside this workspace must map the
workspace package names to the tarballs. With pnpm 11, put this in
\`pnpm-workspace.yaml\`; with pnpm 10, use \`pnpm.overrides\` in \`package.json\`:

\`\`\`yaml
overrides:
  "@banyan/style-contract": "file:./vendor/${exampleArtifact("@banyan/style-contract")}"
  "@banyan/core": "file:./vendor/${exampleArtifact("@banyan/core")}"
  "eslint-plugin-banyan-style": "file:./vendor/${exampleArtifact("eslint-plugin-banyan-style")}"
\`\`\`

Then install all four tarballs in one command. \`pnpm smoke:artifacts\` performs
this check in a temporary directory.

The lint bundle (\`eslint-plugin-banyan-style.mjs\`) plus
\`eslint-plugin-banyan-style.build.json\` is the self-contained copy a host puts
next to its style typings; it does not need the tarball at runtime.

The manifest records the SHA-256 of every file above. A consumer lock should
name \`toolchainRevision\` and verify the artifact hashes before installing.

Files: ${artifactNames.join(", ")}
`,
  "utf8",
);

const packageJSON = JSON.parse(
  await readFile(path.join(rootDir, "package.json"), "utf8"),
);
console.log(
  `packed toolchain artifacts for banyan-toolchain@${packageJSON.version}`,
);
