/**
 * Generate the fixture set: `fixtures/*.rdf`, the JSON item databases
 * (`items-*.json`), the contexts examples, the seed of the item models the
 * tests describe, and `schema/item-database.schema.json`.
 *
 * The RDF is produced by the testkit's own serializer, which mirrors Zotero's
 * "Zotero RDF" export layout, so every fixture is provably a document the
 * exporter could have written. The item models live here rather than in the
 * XML: one place to edit, and `pnpm fixtures` restores the exact files the
 * tests and baselines expect.
 *
 * Two fixtures are hand-authored on purpose: `fixtures/aliases.rdf` covers
 * namespace aliases and `rdf:parseType="Resource"`, which the exporter never
 * emits, and `fixtures/zotero-export.rdf` pins the serializer's real output
 * shape (typed nodes, URL subjects, notes/attachments/collections), which the
 * testkit's own writer does not reproduce verbatim. This script therefore never
 * rewrites them.
 *
 * Run with `pnpm fixtures`.
 */
