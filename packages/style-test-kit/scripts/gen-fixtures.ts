/**
 * The simple JSON database for a model set. It is a direct Banyan-item
 * representation, not an RDF twin: ids are the model keys (`ITEM0001`),
 * fields use the model's names (the loader normalizes base aliases), `extra`
 * becomes a parsed map, and multilingual groups are listed at the database
 * level. Prettier formats the result, so `pnpm fixtures` and `pnpm lint:fix`
 * agree.
 */
async function renderItemDatabase(
  models: readonly ItemModel[],
): Promise<string> {
  const idOf = (model: ItemModel, index: number): string =>
    model.key ?? `item-${index + 1}`;
  const ids = new Map(
    models.map((model, index) => [model.key ?? "", idOf(model, index)]),
  );

  const records = models.map((model, index) => {
    const record: Record<string, unknown> = {
      id: idOf(model, index),
      itemType: model.itemType,
    };
    for (const [name, value] of Object.entries(model.fields)) {
      if (name === "extra") continue;
      record[name] = value;
    }
    if (model.fields.extra) record.extra = parseExtraMap(model.fields.extra);
    if (model.creators.length) record.creators = model.creators;
    if (model.tags?.length) record.tags = model.tags;
    return record;
  });

  const groups = multilingualGroups(models, ids);
  return format(
    JSON.stringify(
      { items: records, ...(groups.length ? { multilingual: groups } : {}) },
      null,
      2,
    ),
    { parser: "json", filepath: "items.json" },
  );
}

/** Connected components of `banyan:multilingual` relations, as id lists. */
function multilingualGroups(
  models: readonly ItemModel[],
  ids: Map<string, string>,
): string[][] {
  const parent = new Map<string, string>();
  const find = (key: string): string => {
    let current = key;
    while (
      parent.get(current) !== undefined &&
      parent.get(current) !== current
    ) {
      current = parent.get(current) as string;
    }
    return current;
  };
  const add = (key: string): void => {
    if (!parent.has(key)) parent.set(key, key);
  };

  for (const model of models) {
    const key = model.key;
    if (!key) continue;
    add(key);
    for (const target of model.relations?.["banyan:multilingual"] ?? []) {
      if (!ids.has(target)) continue;
      add(target);
      const a = find(key);
      const b = find(target);
      if (a !== b) parent.set(b, a);
    }
  }

  const groups = new Map<string, string[]>();
  for (const key of parent.keys()) {
    const root = find(key);
    const list = groups.get(root) ?? [];
    list.push(ids.get(key) ?? key);
    groups.set(root, list);
  }
  return [...groups.values()]
    .filter((group) => group.length > 1)
    .map((group) => group.sort());
}

/** Write the JSON Schema for the simple item database (fixed location). */
async function writeItemDatabaseSchema(): Promise<void> {
  const target = path.resolve(here, "../schema/item-database.schema.json");
  mkdirSync(path.dirname(target), { recursive: true });
  const content = await format(JSON.stringify(ITEM_DATABASE_SCHEMA), {
    parser: "json",
    filepath: "item-database.schema.json",
  });
  writeFileSync(target, content, "utf8");
  console.log(`wrote ${path.relative(process.cwd(), target)}`);
}

