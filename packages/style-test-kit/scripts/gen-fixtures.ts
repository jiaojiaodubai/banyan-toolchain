type ItemModel = Omit<ParsedRdfItem, "node" | "fields" | "creators"> & {
  node: string;
  fields: Record<string, string>;
  creators: ParsedRdfItem["creators"];
  tags?: string[];
};

const HEADER =
  "<!-- Generated by scripts/gen-fixtures.ts — edit the model there, not here. -->";

/** Serialize a model into a fixture document, with a provenance comment. */
function renderFixture(models: readonly ItemModel[]): string {
  const xml = serializeZoteroRdf(
    models.map((model) => ({
      key: model.key,
      itemType: model.itemType,
      fields: model.fields,
      creators: model.creators,
      tags: model.tags,
      relations: model.relations,
    })),
    { nodeId: (record, index) => `#item_${index + 1}` },
  );
  return xml.replace(/(<\?xml[^>]*\?>\n)/, `$1${HEADER}\n`);
}

/** `#item_N` for the key, so relations stay stable when the order changes. */
function nodesByKey(models: readonly ItemModel[]): Map<string, string> {
  const map = new Map<string, string>();
  models.forEach((model, index) => {
    map.set(model.key ?? "", `#item_${index + 1}`);
  });
  return map;
}

/** Rewrite key-based relation targets into node ids. */
function resolveRelations(
  models: readonly ItemModel[],
): Record<string, string[]>[] {
  const nodes = nodesByKey(models);
  return models.map((model) => {
    const relations: Record<string, string[]> = {};
    for (const [predicate, targets] of Object.entries(model.relations ?? {})) {
      relations[predicate] = targets.map(
        (target) => nodes.get(target) ?? target,
      );
    }
    return relations;
  });
}

function applyRelations(models: readonly ItemModel[]): ItemModel[] {
  const resolved = resolveRelations(models);
  return models.map((model, index) => ({
    ...model,
    relations: resolved[index],
  }));
}

