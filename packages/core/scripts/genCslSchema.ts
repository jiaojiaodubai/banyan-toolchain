/**
 * Regenerate the CSL vocabulary the core knows about:
 *
 * - `src/schema/cslSchema.ts` — CSL item types and variables, grouped the way
 *   the CSL schema groups them (standard/date/number/title/string/name)
 * - `src/schema/csl-schema.json` — the same model as a JSON document, for hosts
 *   that want the data at runtime without parsing RELAX NG
 *
 * Source: `node_modules/csl-schema/schemas/styles/{csl-variables,csl-types}.rnc`,
 * i.e. the official Citation Style Language schema repository (a
 * development-time dependency, see `package.json`). The artifacts are committed;
 * nothing reads the source schema at runtime.
 *
 * The core needs this vocabulary to stay compatible with CSL: a variable name
 * that citeproc reads — `type` above all — must not be written as if it were a
 * plain Zotero field.
 *
 * Run with `pnpm gen:schema`.
 */
import { isEntryPoint, readRepoFile, writeGenerated } from "./schemaSource";

export const VARIABLES_PATH =
  "node_modules/csl-schema/schemas/styles/csl-variables.rnc";
export const TYPES_PATH =
  "node_modules/csl-schema/schemas/styles/csl-types.rnc";
export const CSL_SCHEMA_OUTPUT = "src/schema/cslSchema.ts";
export const CSL_JSON_OUTPUT = "src/schema/csl-schema.json";
export const CSL_MODEL_OUTPUT = "src/schema/cslModel.ts";

/** Variable groups, in the order the CSL schema declares them. */
export const CSL_VARIABLE_GROUPS = [
  "dates",
  "names",
  "numbers",
  "titles",
  "strings",
] as const;

export type CslVariableGroup = (typeof CSL_VARIABLE_GROUPS)[number];

/**
 * Blank out RELAX NG compact comments, respecting double-quoted strings, so a
 * quoted example in a comment can never become a CSL variable.
 */
function stripRncComments(source: string): string {
  let out = "";
  let inString = false;
  for (let index = 0; index < source.length; index += 1) {
    const character = source[index];
    if (inString) {
      out += character;
      if (character === '"') inString = false;
      continue;
    }
    if (character === '"') {
      inString = true;
      out += character;
      continue;
    }
    if (character === "#") {
      while (index < source.length && source[index] !== "\n") index += 1;
      out += "\n";
      continue;
    }
    out += character;
  }
  return out;
}

/** Quoted strings inside one RELAX NG assignment, comments ignored. */
function assignedStrings(source: string, assignment: string): string[] {
  const start = source.indexOf(assignment);
  if (start < 0) {
    throw new Error(`The CSL schema has no ${assignment} assignment`);
  }
  // An assignment ends where the next one starts.
  const rest = source.slice(start + assignment.length);
  const next = rest.search(
    /\n\s*(?:variables|item-types)\.[a-z]+ =|\n\s*item-types =/,
  );
  const body = stripRncComments(next < 0 ? rest : rest.slice(0, next));

  const values: string[] = [];
  for (const match of body.matchAll(/"([^"]+)"/g)) {
    const value = match[1];
    if (value !== undefined) {
      values.push(value);
    }
  }
  return Array.from(new Set(values)).sort();
}

export function cslVariables(source: string): Record<string, string[]> {
  const groups: Record<string, string[]> = {};
  for (const group of CSL_VARIABLE_GROUPS) {
    groups[group] = assignedStrings(source, `variables.${group} =`);
  }
  return groups;
}

export function cslItemTypes(source: string): string[] {
  return assignedStrings(source, "item-types =");
}

export function renderCslSchema(source: {
  variables: string;
  types: string;
}): string {
  const groups = cslVariables(source.variables);
  const itemTypes = cslItemTypes(source.types);
  const all = Array.from(new Set(Object.values(groups).flat())).sort();

  const quoteSet = (values: readonly string[], indent = ""): string =>
    `new Set([\n${values
      .map((value) => `${indent}  ${JSON.stringify(value)},`)
      .join("\n")}\n${indent}])`;

  const groupDocs: Record<CslVariableGroup, string> = {
    dates: "Date variables (a date object, e.g. `issued`).",
    names:
      "Name variables (creators; citeproc turns these into names, not text).",
    numbers: "Number variables.",
    titles: "Title variables, including the short forms.",
    strings: "Plain string variables.",
  };

  const groupExports: Record<CslVariableGroup, string> = {
    dates: "CSL_DATE_VARIABLES",
    names: "CSL_NAME_VARIABLES",
    numbers: "CSL_NUMBER_VARIABLES",
    titles: "CSL_TITLE_VARIABLES",
    strings: "CSL_STRING_VARIABLES",
  };

  const groupExportsSource = CSL_VARIABLE_GROUPS.map(
    (group) => `/** ${groupDocs[group]} */
export const ${groupExports[group]}: ReadonlySet<string> = ${quoteSet(
      groups[group] ?? [],
    )};`,
  ).join("\n\n");

  return `/**
 * The CSL vocabulary the core knows about.
 *
 * Generated by \`scripts/genCslSchema.ts\` from the official Citation Style
 * Language schema repository (\`citation-style-language/schema\`, MIT); do not
 * edit this file by hand, re-run \`pnpm gen:schema\` instead.
 *
 * These tables exist so the core can stay compatible with CSL: a style writing
 * a variable citeproc understands must be treated differently from a style
 * writing a plain Zotero field, and CSL item types must be recognizable where a
 * value decides how an item is cited.
 */

/** CSL item types (\`type\` values in CSL data). */
export const CSL_ITEM_TYPES: ReadonlySet<string> = ${quoteSet(itemTypes)};

${groupExportsSource}

/** Every CSL variable, regardless of group. */
export const CSL_VARIABLES: ReadonlySet<string> = ${quoteSet(all)};
`;
}

/**
 * The same vocabulary as data, for runtime consumption.
 *
 * RELAX NG is compact but not something every JavaScript environment can parse,
 * so the core exports the pre-parsed model. Only what the core models is
 * included: item types and the five variable groups (not terms, categories or
 * the style schema itself).
 *
 * The data is emitted twice from this one definition — as the JSON asset
 * (`renderCslSchemaJson`) and as a typed module built into the package index
 * (`renderCslModel`) — the same split as the Zotero model.
 */
export interface CslSchemaJson {
  itemTypes: string[];
  variables: Record<string, string[]>;
  variablesAll: string[];
}

function buildCslModel(source: {
  variables: string;
  types: string;
}): CslSchemaJson {
  const groups = cslVariables(source.variables);
  const itemTypes = cslItemTypes(source.types);
  const all = Array.from(new Set(Object.values(groups).flat())).sort();

  return {
    itemTypes,
    variables: groups,
    variablesAll: all,
  };
}

export function renderCslSchemaJson(source: {
  variables: string;
  types: string;
}): string {
  return JSON.stringify(buildCslModel(source), null, 2);
}

/**
 * The same model as a typed module, for the package index.
 *
 * A module rather than a JSON import, so a host importing `@banyan/core` needs
 * neither a JSON loader nor `resolveJsonModule`; the tests keep it identical to
 * the JSON asset.
 */
export function renderCslModel(source: {
  variables: string;
  types: string;
}): string {
  const model = buildCslModel(source);

  return `/**
 * The CSL vocabulary the core models, for runtime use.
 *
 * Generated by \`scripts/genCslSchema.ts\` from the official Citation Style
 * Language schema repository (\`citation-style-language/schema\`, MIT); do not
 * edit this file by hand, re-run \`pnpm gen:schema\` instead.
 *
 * The same data as \`@banyan/core/schema/csl-schema.json\`, compiled into the
 * module graph so a host that imports the package index can read the vocabulary
 * without a file read, a JSON loader or a \`resolveJsonModule\` setting.
 *
 * RELAX NG is not something every JavaScript environment can parse, which is
 * why the core publishes the parsed form. Only what the core models is here:
 * item types and the five variable groups (not terms, categories or the style
 * schema itself). The constant sets in \`./cslSchema\` are the fast path for
 * membership questions.
 */

/** The CSL vocabulary the core models. */
export interface CslSchemaModel {
  /** CSL item types (\`type\` values in CSL data). */
  readonly itemTypes: readonly string[];
  /** CSL variables by group: \`dates\`, \`names\`, \`numbers\`, \`titles\`, \`strings\`. */
  readonly variables: Readonly<Record<string, readonly string[]>>;
  /** Every CSL variable, regardless of group. */
  readonly variablesAll: readonly string[];
}

/** The CSL vocabulary these artifacts were generated from. */
export const CSL_SCHEMA: CslSchemaModel = ${JSON.stringify(model, null, 2)};
`;
}

async function main(): Promise<void> {
  const source = {
    variables: await readRepoFile(VARIABLES_PATH),
    types: await readRepoFile(TYPES_PATH),
  };
  await writeGenerated(CSL_SCHEMA_OUTPUT, renderCslSchema(source));
  await writeGenerated(CSL_JSON_OUTPUT, renderCslSchemaJson(source));
  await writeGenerated(CSL_MODEL_OUTPUT, renderCslModel(source));

  const groups = cslVariables(source.variables);
  console.log(
    `[gen:schema] CSL schema -> ${CSL_SCHEMA_OUTPUT}, ${CSL_JSON_OUTPUT}, ${CSL_MODEL_OUTPUT} | ` +
      `itemTypes: ${cslItemTypes(source.types).length} | ` +
      `variables: ${Object.values(groups).flat().length} (names: ${groups.names?.length ?? 0})`,
  );
}

if (isEntryPoint(import.meta.url)) {
  await main();
}
