/* global console, process */
/**
 * Generate the executor-neutral schema facts consumed by
 * `@banyan/style-contract`.
 *
 * The source is the same generated vocabulary the core already owns; this
 * script only projects the subset the contract and the linter need. It runs as
 * part of `pnpm gen:schema`, after the Zotero/CSL modules have been written.
 *
 * The output is committed so a checkout can build the contract without first
 * running the schema generators. `pnpm check:schema-facts` verifies freshness.
 */
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  ZOTERO_CREATOR_TYPE_CSL_NAMES,
  ZOTERO_CREATOR_TYPES,
  ZOTERO_ITEM_TYPES,
  ZOTERO_SCHEMA_VERSION,
} from "../src/schema/zoteroSchema.ts";
import {
  CSL_ITEM_TYPES,
  CSL_NAME_VARIABLES,
  CSL_VARIABLES,
} from "../src/schema/cslSchema.ts";
import {
  CSL_M_ITEM_TYPES,
  CSL_M_NAME_VARIABLES,
  CSL_M_ONLY_ITEM_TYPES,
  CSL_M_VARIABLES,
} from "../src/schema/cslmSchema.ts";

const rootDir = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const outputPath = path.resolve(
  rootDir,
  "..",
  "style-contract",
  "src",
  "generated",
  "schema-facts.ts",
);

function sorted(values) {
  return [...values].sort((left, right) => left.localeCompare(right));
}

function sha256(buffer) {
  return createHash("sha256").update(buffer).digest("hex");
}

function shortHash(buffer) {
  return sha256(buffer).slice(0, 12);
}

const [zoteroBuffer, cslBuffer, cslmBuffer] = await Promise.all([
  readFile(path.join(rootDir, "src", "schema", "zotero-schema.json")),
  readFile(path.join(rootDir, "src", "schema", "csl-schema.json")),
  readFile(path.join(rootDir, "src", "schema", "cslmSchema.ts")),
]);

const zoteroRevision = shortHash(zoteroBuffer);
const cslRevision = shortHash(cslBuffer);
const cslmRevision = shortHash(cslmBuffer);
const schemaRevision = `zotero-${ZOTERO_SCHEMA_VERSION}+csl-${cslRevision}+cslm-${cslmRevision}`;

const facts = {
  schemaRevision,
  zoteroSchemaRevision: zoteroRevision,
  cslSchemaRevision: cslRevision,
  zoteroSchemaVersion: ZOTERO_SCHEMA_VERSION,
  zoteroItemTypes: sorted(ZOTERO_ITEM_TYPES),
  zoteroCreatorTypes: sorted(ZOTERO_CREATOR_TYPES),
  zoteroCreatorTypeCslNames: Object.fromEntries(
    Object.entries(ZOTERO_CREATOR_TYPE_CSL_NAMES).sort(([left], [right]) =>
      left.localeCompare(right),
    ),
  ),
  cslItemTypes: sorted(CSL_ITEM_TYPES),
  cslVariables: sorted(CSL_VARIABLES),
  cslNameVariables: sorted(CSL_NAME_VARIABLES),
  cslmItemTypes: sorted(CSL_M_ITEM_TYPES),
  cslmOnlyItemTypes: sorted(CSL_M_ONLY_ITEM_TYPES),
  cslmVariables: sorted(CSL_M_VARIABLES),
  cslmNameVariables: sorted(CSL_M_NAME_VARIABLES),
};

const content = `// Generated by packages/core/scripts/genStyleContractFacts.mjs.
// Do not edit by hand: run \`pnpm gen:schema\` from the toolchain root.
//
// Schema revision: ${schemaRevision}
// Zotero model: ${ZOTERO_SCHEMA_VERSION}
// CSL asset: ${cslRevision}
// CSL-M source: ${cslmRevision}

import type { SchemaFacts } from "../constants.js";

export const SCHEMA_FACTS = ${JSON.stringify(facts, null, 2)} as const satisfies SchemaFacts;
`;

const checkOnly = process.argv.includes("--check");
const existing = checkOnly
  ? await readFile(outputPath, "utf8").catch(() => "")
  : "";

if (checkOnly) {
  if (existing !== content) {
    console.error(
      `stale ${path.relative(rootDir, outputPath)}; run \`pnpm gen:schema\``,
    );
    process.exitCode = 1;
  } else {
    console.log(`up to date: ${path.relative(rootDir, outputPath)}`);
  }
} else {
  await writeFile(outputPath, content, "utf8");
  console.log(
    `wrote ${path.relative(rootDir, outputPath)} (${schemaRevision})`,
  );
}
